def story_templates(rows: list[dict]) -> dict[str, dict]:
    templates = {}
    for row in rows:
        templates.setdefault(row["name"], row)
    return templates


def compute_locked_pca_regressors(
    args: argparse.Namespace,
    heldout_rows: list[dict],
    output_dir: Path,
) -> Path:
    regressor_dir = output_dir / "heldout_regressors"
    regressor_dir.mkdir(parents=True, exist_ok=True)
    expected = [regressor_dir / f"{story}_shared_pca_regressors.csv" for story in HELDOUT_STORIES]
    if args.resume and all(path.exists() for path in expected):
        print("Using cached held-out regressors", flush=True)
        return regressor_dir

    discovery_rows = load_story_list(str(ROOT / args.discovery_subject_list))
    discovery_templates = {row["name"]: row for row in get_unique_stories(discovery_rows)}
    heldout_templates = story_templates(heldout_rows)
    missing_discovery = [story for story in DISCOVERY_STORIES if story not in discovery_templates]
    missing_heldout = [story for story in HELDOUT_STORIES if story not in heldout_templates]
    if missing_discovery or missing_heldout:
        raise ValueError(
            f"Missing story templates; discovery={missing_discovery}, heldout={missing_heldout}"
        )

    tokenizer, model, device = load_gpt2()
    model.eval()
    embeddings = {}
    baseline_data = {}
    templates = {**discovery_templates, **heldout_templates}
    for story in DISCOVERY_STORIES + HELDOUT_STORIES:
        template = templates[story]
        chunks, onset, duration, _ = transcript_to_tr_chunks_uniform(template, tr=1.5)
        print(f"Computing locked cumulative embeddings: {story}", flush=True)
        embeddings[story] = cumulative_current_token_embeddings(
            chunks,
            tokenizer,
            model,
            layer=12,
            max_length=1024,
            output_stride=256,
            device=device,
        )
        baseline_data[story] = (chunks, onset, duration, template)

    discovery_matrix = np.vstack([embeddings[story] for story in DISCOVERY_STORIES])
    scaler = StandardScaler()
    scaler.fit(discovery_matrix)
    pca = PCA(n_components=5)
    pca.fit(scaler.transform(discovery_matrix))
    scores = {
        story: pca.transform(scaler.transform(embeddings[story]))
        for story in DISCOVERY_STORIES + HELDOUT_STORIES
    }

    existing_dir = ROOT / args.existing_cumulative_regressor_dir
    audit_rows = []
    component_signs = np.ones(5, dtype=float)
    projected_all = np.vstack([scores[story] for story in DISCOVERY_STORIES])
    existing_all = np.vstack(
        [
            pd.read_csv(existing_dir / f"{story}_shared_pca_regressors.csv")[
                [f"PC{i}" for i in range(1, 6)]
            ].to_numpy(dtype=float)
            for story in DISCOVERY_STORIES
        ]
    )
    for component in range(5):
        correlation = float(stats.pearsonr(projected_all[:, component], existing_all[:, component]).statistic)
        component_signs[component] = 1.0 if correlation >= 0 else -1.0
    for story in scores:
        scores[story] = scores[story] * component_signs

    for story in DISCOVERY_STORIES:
        existing = pd.read_csv(existing_dir / f"{story}_shared_pca_regressors.csv")
        existing_scores = existing[[f"PC{i}" for i in range(1, 6)]].to_numpy(dtype=float)
        current = scores[story]
        if len(current) != len(existing_scores):
            raise ValueError(
                f"Locked PCA audit length differs for {story}: {len(current)} vs {len(existing_scores)}"
            )
        for component in range(5):
            audit_rows.append(
                {
                    "story": story,
                    "component": component + 1,
                    "correlation": float(
                        stats.pearsonr(current[:, component], existing_scores[:, component]).statistic
                    ),
                    "max_absolute_error": float(
                        np.max(np.abs(current[:, component] - existing_scores[:, component]))
                    ),
                }
            )
    audit = pd.DataFrame(audit_rows)
    audit.to_csv(output_dir / "locked_pca_reproduction_audit.csv", index=False)
    if float(audit["correlation"].min()) < 0.999:
        raise RuntimeError(
            "The discovery-story PCA could not be reproduced closely enough to project held-out stories."
        )

    pd.DataFrame(
        {
            "component": [f"PC{i}" for i in range(1, 6)],
            "explained_variance_ratio": pca.explained_variance_ratio_,
            "alignment_sign": component_signs,
        }
    ).to_csv(output_dir / "locked_pca_metadata.csv", index=False)

    for story in HELDOUT_STORIES:
        chunks, onset, duration, template = baseline_data[story]
        baseline = compute_text_baselines(chunks)
        acoustic = compute_acoustic_control_baselines(template, tr=1.5)
        baseline = baseline.merge(acoustic, on="time_TR", how="left")
        for column in acoustic.columns:
            if column != "time_TR":
                baseline[column] = baseline[column].fillna(0.0)
        baseline["story"] = story
        baseline["TR"] = 1.5
        baseline["onset_sec"] = onset
        baseline["duration_sec"] = duration
        for column in [
            "word_count",
            "mean_char_len",
            "total_chars",
            "speech_duration_sec",
            "mean_word_duration_sec",
            "pause_fraction",
            "articulation_rate",
            "word_rate",
            "audio_rms",
            "audio_abs_mean",
        ]:
            if column in baseline:
                baseline[f"{column}_hrf"] = hrf_convolve(
                    baseline[column].to_numpy(dtype=float), tr=1.5
                )
        for component in range(5):
            column = f"PC{component + 1}"
            baseline[column] = scores[story][:, component]
            baseline[f"{column}_hrf"] = hrf_convolve(
                scores[story][:, component], tr=1.5
            )

        rich = compute_rich_audio_features(template, Path(args.gentle_root), tr=1.5)
        for column in RICH_AUDIO_COLUMNS:
            rich[f"{column}_hrf"] = hrf_convolve(
                rich[column].to_numpy(dtype=float), tr=1.5
            )
        output = baseline.merge(
            rich[
                ["time_TR"]
                + RICH_AUDIO_COLUMNS
                + [f"{column}_hrf" for column in RICH_AUDIO_COLUMNS]
            ],
            on="time_TR",
            how="left",
        )
        for column in RICH_AUDIO_COLUMNS + [f"{column}_hrf" for column in RICH_AUDIO_COLUMNS]:
            output[column] = output[column].fillna(0.0)
        output.to_csv(regressor_dir / f"{story}_shared_pca_regressors.csv", index=False)
        print(f"Saved held-out regressors: {story}", flush=True)
    return regressor_dir


def extract_heldout_rois(
    args: argparse.Namespace,
    heldout_rows: list[dict],
    output_dir: Path,
) -> Path:
    cache_dir = output_dir / "roi_cache"
    cache_dir.mkdir(parents=True, exist_ok=True)
    atlas_img, atlas_labels = fetch_harvard_oxford_atlas()
    for index, story in enumerate(heldout_rows, start=1):
        print(
            f"ROI extraction [{index}/{len(heldout_rows)}] "
            f"{story['name']} {story['subject']}",
            flush=True,
        )
        load_or_extract_roi_matrix(
            story,
            atlas_img,
            atlas_labels,
            cache_dir,
            atlas_threshold=0.0,
        )
    return cache_dir


def heldout_design(regressor_dir: Path, story: str) -> dict[str, np.ndarray]:
    reg = pd.read_csv(regressor_dir / f"{story}_shared_pca_regressors.csv")
    existing_acoustic = [
        f"{column}_hrf"
        for column in ACOUSTIC_CONTROL_COLUMNS
        if f"{column}_hrf" in reg.columns
    ]
    rich_audio = [f"{column}_hrf" for column in RICH_AUDIO_COLUMNS]
    baseline_columns = list(LEXICAL_BASELINE_COLS) + existing_acoustic + rich_audio
    pc_columns = [f"PC{i}_hrf" for i in range(1, 6)]
    baseline = reg[baseline_columns].to_numpy(dtype=float)
    pcs = reg[pc_columns].to_numpy(dtype=float)
    return {
        "baseline": baseline,
        "combined": np.column_stack([baseline, pcs]),
        "pcs": pcs,
    }


def evaluate_replication(
    args: argparse.Namespace,
    cache_dir: Path,
    regressor_dir: Path,
    output_dir: Path,
) -> None:
    story_data = {}
    for story in HELDOUT_STORIES:
        targets, roi_names = load_story_targets(cache_dir, story)
        design = heldout_design(regressor_dir, story)
        story_data[story] = (targets, roi_names, design)
        print(f"Loaded held-out analysis data: {story} {targets.shape}", flush=True)

    full_rows = []
    split_rows = []
    leave_rows = []
    prepared_null = {}
    for story, (targets, roi_names, design) in story_data.items():
        group_target = np.mean(targets, axis=0)
        baseline_r, _ = vectorized_cv_r(
            design["baseline"], group_target, args.n_splits, args.alpha, True, args.cv_gap
        )
        combined_r, _ = vectorized_cv_r(
            design["combined"], group_target, args.n_splits, args.alpha, True, args.cv_gap
        )
        for roi_index, roi in enumerate(roi_names):
            full_rows.append(
                {
                    "story": story,
                    "roi": roi,
                    "baseline_cv_r": baseline_r[roi_index],
                    "combined_cv_r": combined_r[roi_index],
                    "delta_cv_r": combined_r[roi_index] - baseline_r[roi_index],
                }
            )
        prepared_null[story] = (group_target, design, baseline_r)

        for seed in range(args.subject_splits):
            indices = np.random.default_rng(seed).permutation(len(targets))
            first = indices[: len(indices) // 2]
            second = indices[len(indices) // 2 :]
            baseline_split = (
                cross_group_cv_r(
                    design["baseline"], targets, first, second,
                    args.n_splits, args.alpha, args.cv_gap,
                )
                + cross_group_cv_r(
                    design["baseline"], targets, second, first,
                    args.n_splits, args.alpha, args.cv_gap,
                )
            ) / 2.0
            combined_split = (
                cross_group_cv_r(
                    design["combined"], targets, first, second,
                    args.n_splits, args.alpha, args.cv_gap,
                )
                + cross_group_cv_r(
                    design["combined"], targets, second, first,
                    args.n_splits, args.alpha, args.cv_gap,
                )
            ) / 2.0
            split_rows.append(
                {
                    "story": story,
                    "seed": seed,
                    "mean_delta_cv_r": float(np.mean(combined_split - baseline_split)),
                }
            )

        cache_files = sorted(cache_dir.glob(f"{story}_*.npz"))
        subjects = [path.stem[len(story) + 1 :] for path in cache_files]
        all_subjects = np.arange(len(targets))
        for heldout_index, subject in enumerate(subjects):
            training = all_subjects[all_subjects != heldout_index]
            testing = np.asarray([heldout_index])
            baseline_leave = cross_group_cv_r(
                design["baseline"], targets, training, testing,
                args.n_splits, args.alpha, args.cv_gap,
            )
            combined_leave = cross_group_cv_r(
                design["combined"], targets, training, testing,
                args.n_splits, args.alpha, args.cv_gap,
            )
            leave_rows.append(
                {
                    "story": story,
                    "subject": subject,
                    "mean_delta_cv_r": float(np.mean(combined_leave - baseline_leave)),
                }
            )

    full = pd.DataFrame(full_rows)
    split = pd.DataFrame(split_rows)
    leave = pd.DataFrame(leave_rows)
    full_story = full.groupby("story", as_index=False).delta_cv_r.mean()
    split_story = split.groupby("story", as_index=False).mean_delta_cv_r.mean()
    leave_story = leave.groupby("story", as_index=False).mean_delta_cv_r.mean()

    summary_rows = []
    for label, table, column in [
        ("full_group", full_story, "delta_cv_r"),
        ("held_out_participant_split_half", split_story, "mean_delta_cv_r"),
        ("leave_one_participant_out", leave_story, "mean_delta_cv_r"),
    ]:
        row = {"analysis": label, "scope": "heldout_three_stories"}
        row.update(one_sample_summary(table[column]))
        summary_rows.append(row)

    original_dir = ROOT / args.original_validation_dir
    original_full = pd.read_csv(original_dir / "full_group_story_means.csv")[
        ["story", "cumulative_context_additive"]
    ].rename(columns={"cumulative_context_additive": "delta"})
    original_split = pd.read_csv(original_dir / "split_half_story_means.csv")[
        ["story", "cumulative_context_additive"]
    ].rename(columns={"cumulative_context_additive": "delta"})
    expanded_full = pd.concat(
        [
            original_full,
            full_story.rename(columns={"delta_cv_r": "delta"}),
        ],
        ignore_index=True,
    )
    expanded_split = pd.concat(
        [
            original_split,
            split_story.rename(columns={"mean_delta_cv_r": "delta"}),
        ],
        ignore_index=True,
    )
    for label, table in [
        ("full_group", expanded_full),
        ("held_out_participant_split_half", expanded_split),
    ]:
        row = {"analysis": label, "scope": "expanded_eleven_stories"}
        row.update(one_sample_summary(table["delta"]))
        summary_rows.append(row)

    observed = float(full_story["delta_cv_r"].mean())
    rng = np.random.default_rng(args.random_seed)
    null_rows = []
    for permutation in range(args.circular_shifts):
        values = []
        shifts = []
        for story, (group_target, design, baseline_r) in prepared_null.items():
            minimum = min(args.minimum_shift_trs, max(1, len(design["pcs"]) // 4))
            shift = int(rng.integers(minimum, len(design["pcs"]) - minimum))
            shifted = np.roll(design["pcs"], shift, axis=0)
            shifted_r, _ = vectorized_cv_r(
                np.column_stack([design["baseline"], shifted]),
                group_target,
                args.n_splits,
                args.alpha,
                True,
                args.cv_gap,
            )
            values.append(float(np.mean(shifted_r - baseline_r)))
            shifts.append(f"{story}:{shift}")
        null_rows.append(
            {
                "permutation": permutation,
                "null_mean_delta": float(np.mean(values)),
                "shifts": ";".join(shifts),
            }
        )
    null = pd.DataFrame(null_rows)
    p_shift = float(
        (1 + np.sum(null["null_mean_delta"].to_numpy() >= observed))
        / (len(null) + 1)
    )
    shift_summary = pd.DataFrame(
        [
            {
                "observed_mean_delta": observed,
                "n_permutations": len(null),
                "null_mean": float(null["null_mean_delta"].mean()),
                "null_std": float(null["null_mean_delta"].std(ddof=1)),
                "null_95th_percentile": float(null["null_mean_delta"].quantile(0.95)),
                "p_circular_shift_greater": p_shift,
            }
        ]
    )

    full.to_csv(output_dir / "heldout_full_group_long.csv", index=False)
    split.to_csv(output_dir / "heldout_split_half.csv", index=False)
    leave.to_csv(output_dir / "heldout_leave_one_participant_out.csv", index=False)
    full_story.to_csv(output_dir / "heldout_full_group_story_means.csv", index=False)
    split_story.to_csv(output_dir / "heldout_split_half_story_means.csv", index=False)
    leave_story.to_csv(output_dir / "heldout_leave_one_participant_out_story_means.csv", index=False)
    expanded_full.to_csv(output_dir / "expanded_eleven_story_full_group.csv", index=False)
    expanded_split.to_csv(output_dir / "expanded_eleven_story_split_half.csv", index=False)
    pd.DataFrame(summary_rows).to_csv(output_dir / "heldout_and_expanded_summary.csv", index=False)
    null.to_csv(output_dir / "heldout_circular_shift_null.csv", index=False)
    shift_summary.to_csv(output_dir / "heldout_circular_shift_summary.csv", index=False)

    print("\nHeld-out and expanded story inference:\n", flush=True)
    print(pd.DataFrame(summary_rows).to_string(index=False), flush=True)
    print("\nHeld-out circular-shift inference:\n", flush=True)
    print(shift_summary.to_string(index=False), flush=True)


