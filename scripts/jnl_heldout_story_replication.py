def subject_from_event(path: Path) -> str:
    match = re.search(r"(sub-[A-Za-z0-9]+)", path.name)
    if match is None:
        raise ValueError(f"Cannot parse subject from {path}")
    return match.group(1)


def choose_existing(paths: list[Path], label: str) -> Path:
    matches = [path for path in paths if path.exists()]
    if not matches:
        raise FileNotFoundError(label)
    return matches[0]


def build_heldout_rows(args: argparse.Namespace, output_dir: Path) -> list[dict]:
    dataset_dir = ROOT / args.dataset_dir
    fmriprep_dir = Path(args.fmriprep_dir)
    rows = []
    qc_rows = []

    for story in HELDOUT_STORIES:
        events = sorted(dataset_dir.glob(f"sub-*/func/*_task-{story}_events.tsv"))
        for event_path in events:
            subject = subject_from_event(event_path)
            func_dir = fmriprep_dir / subject / "func"
            bold = choose_existing(
                [
                    func_dir
                    / (
                        f"{subject}_task-{story}_space-MNI152NLin2009cAsym_"
                        "res-native_desc-preproc_bold.nii.gz"
                    ),
                    func_dir
                    / (
                        f"{subject}_task-{story}_space-MNI152NLin6Asym_"
                        "res-native_desc-preproc_bold.nii.gz"
                    ),
                ],
                f"MNI preprocessed BOLD for {subject} {story}",
            )
            confounds = choose_existing(
                [
                    func_dir / f"{subject}_task-{story}_desc-confounds_timeseries.tsv",
                    func_dir / f"{subject}_task-{story}_desc-confounds_regressors.tsv",
                ],
                f"confounds for {subject} {story}",
            )
            qc = summarize_confounds(str(confounds))
            keep = (
                qc["mean_fd"] <= args.max_mean_fd
                and qc["pct_fd_gt_0_5"] <= args.max_pct_fd_gt_0_5
            )
            qc_rows.append(
                {
                    "story": story,
                    "subject": subject,
                    "keep_motion_qc": keep,
                    **qc,
                }
            )
            if not keep:
                continue
            rows.append(
                {
                    "name": story,
                    "subject": subject,
                    "bold_file": bold.as_posix(),
                    "events_file": event_path.as_posix(),
                    "transcript_file": (
                        ROOT / "data" / "transcripts" / f"{story}_transcript.txt"
                    ).as_posix(),
                    "bold_source": "fmriprep_mni",
                    "confounds_file": confounds.as_posix(),
                    "confounds_source": "fmriprep",
                }
            )

    pd.DataFrame(qc_rows).to_csv(output_dir / "heldout_motion_qc.csv", index=False)
    config_path = output_dir / "heldout_motionfiltered_config.py"
    config_path.write_text(
        "# Generated by scripts/jnl_heldout_story_replication.py\n\n"
        + "stories = "
        + json.dumps(rows, indent=4)
        + "\n",
        encoding="utf-8",
    )
    counts = pd.Series([row["name"] for row in rows]).value_counts().to_dict()
    print(f"Held-out motion-QC counts: {counts}", flush=True)
    return rows


